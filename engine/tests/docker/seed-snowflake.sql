CREATE OR REPLACE TABLE COUNTRIES (ID NUMBER(38,0) NOT NULL CONSTRAINT PK_COUNTRIES PRIMARY KEY, NAME VARCHAR(100) NOT NULL);

CREATE OR REPLACE TABLE CUSTOMERS (
    ID NUMBER(38,0) IDENTITY(1, 1) NOT NULL CONSTRAINT PK_CUSTOMERS PRIMARY KEY,
    NAME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(200),
    COUNTRY_ID NUMBER(38,0) CONSTRAINT FK_CUSTOMERS_COUNTRIES REFERENCES COUNTRIES (ID));

CREATE OR REPLACE TABLE ORDERS (
    ID NUMBER(38,0) NOT NULL CONSTRAINT PK_ORDERS PRIMARY KEY,
    CUSTOMER_ID NUMBER(38,0) NOT NULL CONSTRAINT FK_ORDERS_CUSTOMERS REFERENCES CUSTOMERS (ID),
    ORDER_DATE TIMESTAMP_NTZ NOT NULL,
    TOTAL NUMBER(12,2) NOT NULL);

CREATE OR REPLACE TABLE PRODUCTS (ID NUMBER(38,0) NOT NULL CONSTRAINT PK_PRODUCTS PRIMARY KEY, NAME VARCHAR(100) NOT NULL, PRICE NUMBER(10,2));

CREATE OR REPLACE TABLE ORDER_LINES (
    ORDER_ID NUMBER(38,0) NOT NULL CONSTRAINT FK_ORDER_LINES_ORDERS REFERENCES ORDERS (ID),
    PRODUCT_ID NUMBER(38,0) NOT NULL CONSTRAINT FK_ORDER_LINES_PRODUCTS REFERENCES PRODUCTS (ID),
    QTY NUMBER(38,0) NOT NULL DEFAULT 1,
    CONSTRAINT PK_ORDER_LINES PRIMARY KEY (ORDER_ID, PRODUCT_ID));

