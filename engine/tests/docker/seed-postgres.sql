-- DbStudio "shop" fixture for PostgreSQL (docs/PLAN-PG.md 2.10, docs/PLAN.md 4.14). Idempotent.
-- Same data as ShopSchema: 3 countries, 5 customers, 6 orders (order 1 total 120.50), 4 products, 7 order lines,
-- plus PostgreSQL extras: schema sales, enum, domain, sequence, identity/serial/generated/array/jsonb columns,
-- INCLUDE and partial indexes, view, materialized view, overloaded functions, a set-returning function,
-- procedures with RAISE NOTICE/WARNING and INOUT, a trigger with its trigger function, and comments.
DROP SCHEMA IF EXISTS sales CASCADE;
DROP MATERIALIZED VIEW IF EXISTS public.customer_totals;
DROP VIEW IF EXISTS public.customer_orders;
DROP TABLE IF EXISTS public.extra_types, public.order_lines, public.orders, public.products, public.customers, public.countries CASCADE;
DROP FUNCTION IF EXISTS public.fn_tax(numeric), public.fn_tax(numeric, numeric), public.orders_of(integer), public.orders_check();
DROP PROCEDURE IF EXISTS public.add_order_line(integer, integer, integer, integer), public.get_customer_report(integer);
DROP TYPE IF EXISTS public.order_status;
DROP DOMAIN IF EXISTS public.email_address;
DROP SEQUENCE IF EXISTS public.order_numbers;

CREATE SCHEMA sales;
CREATE TYPE public.order_status AS ENUM ('new', 'paid', 'shipped', 'cancelled');
CREATE DOMAIN public.email_address AS text CHECK (VALUE ~ '@');
CREATE SEQUENCE public.order_numbers START WITH 1000;

CREATE TABLE public.countries (id integer PRIMARY KEY, name text NOT NULL);
CREATE TABLE public.customers (
  id integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_customers PRIMARY KEY,
  name varchar(100) NOT NULL,
  email public.email_address,
  country_id integer CONSTRAINT fk_customers_countries REFERENCES public.countries(id));
COMMENT ON TABLE public.customers IS 'Registered customers';
COMMENT ON COLUMN public.customers.name IS 'Display name';
CREATE TABLE public.orders (
  id integer CONSTRAINT pk_orders PRIMARY KEY,
  customer_id integer NOT NULL CONSTRAINT fk_orders_customers REFERENCES public.customers(id),
  order_date timestamptz NOT NULL,
  total numeric(12,2) NOT NULL,
  status public.order_status NOT NULL DEFAULT 'new');
CREATE TABLE public.products (id integer PRIMARY KEY, name text NOT NULL, price numeric(10,2));
CREATE TABLE public.order_lines (
  order_id integer NOT NULL CONSTRAINT fk_order_lines_orders REFERENCES public.orders(id),
  product_id integer NOT NULL CONSTRAINT fk_order_lines_products REFERENCES public.products(id),
  qty integer NOT NULL DEFAULT 1,
  line_total numeric(12,2) GENERATED ALWAYS AS (qty * 1.0) STORED,
  CONSTRAINT pk_order_lines PRIMARY KEY (order_id, product_id));
CREATE TABLE sales.invoices (
  id integer PRIMARY KEY,
  order_id integer NOT NULL CONSTRAINT fk_invoices_orders REFERENCES public.orders(id),
  amount numeric(12,2) NOT NULL);
CREATE TABLE public.extra_types (
  id serial PRIMARY KEY, tags text[], meta jsonb, ext_id uuid DEFAULT gen_random_uuid(), span interval,
  created timestamptz DEFAULT now(), pos point, ip inet, raw bytea, flags bit(4));
CREATE INDEX ix_orders_customer ON public.orders (customer_id) INCLUDE (total);
CREATE INDEX ix_orders_open ON public.orders (order_date) WHERE status <> 'cancelled';

