CREATE VIEW public.customer_orders AS
SELECT c.id AS customer_id, c.name, o.id AS order_id, o.total
FROM public.customers c JOIN public.orders o ON o.customer_id = c.id;
CREATE MATERIALIZED VIEW public.customer_totals AS
SELECT c.id AS customer_id, c.name, count(o.id) AS orders, coalesce(sum(o.total), 0) AS revenue
FROM public.customers c LEFT JOIN public.orders o ON o.customer_id = c.id GROUP BY c.id, c.name;

CREATE FUNCTION public.fn_tax(amount numeric) RETURNS numeric LANGUAGE sql IMMUTABLE AS $$ SELECT amount * 0.19 $$;
CREATE FUNCTION public.fn_tax(amount numeric, rate numeric) RETURNS numeric LANGUAGE sql IMMUTABLE AS $$ SELECT amount * rate $$;
CREATE FUNCTION public.orders_of(p_customer integer) RETURNS TABLE (id integer, order_date timestamptz, total numeric)
LANGUAGE sql STABLE AS $$ SELECT o.id, o.order_date, o.total FROM public.orders o WHERE o.customer_id = p_customer ORDER BY o.id $$;
CREATE PROCEDURE public.add_order_line(p_order integer, p_product integer, p_qty integer, INOUT inserted integer) LANGUAGE plpgsql AS $$
BEGIN
  INSERT INTO public.order_lines (order_id, product_id, qty) VALUES (p_order, p_product, p_qty);
  GET DIAGNOSTICS inserted = ROW_COUNT;
END $$;
CREATE PROCEDURE public.get_customer_report(p_id integer) LANGUAGE plpgsql AS $$
DECLARE v_name text;
BEGIN
  SELECT name INTO v_name FROM public.customers WHERE id = p_id;
  RAISE NOTICE 'Report for customer %', coalesce(v_name, '?');
  IF v_name IS NULL THEN RAISE WARNING 'Customer % not found', p_id; END IF;
END $$;
CREATE FUNCTION public.orders_check() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.total < 0 THEN RAISE EXCEPTION 'negative total' USING ERRCODE = '23514'; END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_orders_check BEFORE INSERT ON public.orders FOR EACH ROW EXECUTE FUNCTION public.orders_check();
