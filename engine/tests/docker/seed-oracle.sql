CREATE VIEW CUSTOMER_ORDERS AS
SELECT c.ID AS CUSTOMER_ID, c.NAME, o.ID AS ORDER_ID, o.TOTAL
FROM CUSTOMERS c JOIN ORDERS o ON o.CUSTOMER_ID = c.ID
/
CREATE SEQUENCE ORDERS_SEQ START WITH 100
/
CREATE SYNONYM CUST FOR SHOP.CUSTOMERS
/
CREATE OR REPLACE FUNCTION FN_TAX(p_amount IN NUMBER) RETURN NUMBER IS
BEGIN
  RETURN ROUND(p_amount * 0.19, 2);
END FN_TAX;
/
CREATE OR REPLACE PACKAGE ORDER_API AS
  PROCEDURE CREATE_ORDER(p_cust IN NUMBER, p_total IN NUMBER);
  FUNCTION GET_TOTAL(p_id NUMBER) RETURN NUMBER;
  -- Overload: total with tax added when p_with_tax = 'Y'.
  FUNCTION GET_TOTAL(p_id NUMBER, p_with_tax IN VARCHAR2) RETURN NUMBER;
END ORDER_API;
/
CREATE OR REPLACE PACKAGE BODY ORDER_API AS
  PROCEDURE CREATE_ORDER(p_cust IN NUMBER, p_total IN NUMBER) IS
  BEGIN
    INSERT INTO ORDERS (ID, CUSTOMER_ID, ORDER_DATE, TOTAL) VALUES (ORDERS_SEQ.NEXTVAL, p_cust, SYSDATE, p_total);
  END CREATE_ORDER;

  FUNCTION GET_TOTAL(p_id NUMBER) RETURN NUMBER IS
    v NUMBER;
  BEGIN
    SELECT TOTAL INTO v FROM ORDERS WHERE ID = p_id;
    RETURN v;
  END GET_TOTAL;

  FUNCTION GET_TOTAL(p_id NUMBER, p_with_tax IN VARCHAR2) RETURN NUMBER IS
  BEGIN
    RETURN CASE WHEN p_with_tax = 'Y' THEN FN_TAX(GET_TOTAL(p_id)) + GET_TOTAL(p_id) ELSE GET_TOTAL(p_id) END;
  END GET_TOTAL;
END ORDER_API;
/
-- DBMS_OUTPUT producer.
CREATE OR REPLACE PROCEDURE PRINT_CUSTOMER(p_id IN NUMBER) IS
BEGIN
  FOR c IN (SELECT NAME, EMAIL FROM CUSTOMERS WHERE ID = p_id) LOOP
    DBMS_OUTPUT.PUT_LINE('Customer: ' || c.NAME);
    DBMS_OUTPUT.PUT_LINE('Email: ' || NVL(c.EMAIL, '-'));
  END LOOP;
END PRINT_CUSTOMER;
/
-- Two implicit result sets (12c+ DBMS_SQL.RETURN_RESULT).
CREATE OR REPLACE PROCEDURE CUSTOMER_REPORT(p_id IN NUMBER) IS
  c1 SYS_REFCURSOR;
  c2 SYS_REFCURSOR;
BEGIN
  OPEN c1 FOR SELECT ID, NAME, EMAIL FROM CUSTOMERS WHERE ID = p_id;
  DBMS_SQL.RETURN_RESULT(c1);
  OPEN c2 FOR SELECT ID, ORDER_DATE, TOTAL FROM ORDERS WHERE CUSTOMER_ID = p_id ORDER BY ID;
  DBMS_SQL.RETURN_RESULT(c2);
END CUSTOMER_REPORT;
