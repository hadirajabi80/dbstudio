-- rebuildRequired: false, transactional: false

-- [create]
CREATE TABLE SHOP.ORDERS (
    ID NUMBER(10) NOT NULL,
    CUSTOMER_ID NUMBER(10) NOT NULL,
    ORDER_DATE DATE NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'new' NOT NULL,
    TOTAL NUMBER(12,2) DEFAULT 0 NOT NULL,
    NOTE VARCHAR2(200),
    CONSTRAINT PK_ORDERS PRIMARY KEY (ID),
    CONSTRAINT UQ_ORDERS_CUSTOMER_DATE UNIQUE (CUSTOMER_ID, ORDER_DATE),
    CONSTRAINT CK_ORDERS_TOTAL CHECK (TOTAL >= 0),
    CONSTRAINT FK_ORDERS_CUSTOMERS FOREIGN KEY (CUSTOMER_ID) REFERENCES SHOP.CUSTOMERS (ID)
);

-- [index]
CREATE INDEX SHOP.IX_ORDERS_CUSTOMER_ID ON SHOP.ORDERS (CUSTOMER_ID);

-- [comment]
COMMENT ON TABLE SHOP.ORDERS IS 'Customer orders';

-- [comment]
COMMENT ON COLUMN SHOP.ORDERS.NOTE IS 'Free text';
