    [Fact]
    public void Identity_CreateAndAlter_Golden()
    {
        var orders = DesignerCases.Orders(Dialect.PlSql);
        var create = orders with { Columns = orders.Columns.Select(c => c.Name == "ID" ? c with { Identity = new IdentityModel(1, 1, Always: true) } : c).ToList() };
        var created = Scripter.ScriptTable(null, create, Context);
        Assert.Contains("    ID NUMBER(10) GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,", created.Statements[0].Sql);
        Golden.Match("plsql_identity_create.sql", Golden.Render(created));

        // ORA-30673: an existing non-identity column cannot become an identity. The design is refused (400 VALIDATION)
        // instead of scripting DDL that always fails.
        var addIdentity = Assert.Throws<ArgumentException>(() =>
            Scripter.ScriptTable(orders, orders with { Columns = orders.Columns.Select(c => c.Name == "ID" ? c with { Identity = new IdentityModel(100, 10) } : c).ToList() }, Context));
        Assert.Equal("Oracle cannot add an identity to an existing column (ID); add a new identity column instead.", addIdentity.Message);

        // An existing identity can be changed (start / increment / ALWAYS) and dropped.
        var alterIdentity = Scripter.ScriptTable(create, orders with { Columns = orders.Columns.Select(c => c.Name == "ID" ? c with { Identity = new IdentityModel(100, 10) } : c).ToList() }, Context);
        Assert.Equal("ALTER TABLE SHOP.ORDERS MODIFY ID GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 10)", Assert.Single(alterIdentity.Statements).Sql);
        var dropIdentity = Scripter.ScriptTable(create, orders, Context);
        Assert.Equal("ALTER TABLE SHOP.ORDERS MODIFY ID DROP IDENTITY", Assert.Single(dropIdentity.Statements).Sql);
        Golden.Match("plsql_identity_alter.sql", Golden.Render(alterIdentity));
    }

