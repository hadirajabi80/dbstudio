    [SkippableFact]
    public async Task M15_RefCursorOutParam_ReturnsRowsAsResultSet()
    {
        RequireAvailable();
        await using var session = await Fixture.OpenSessionAsync();
        var (summary, sink) = await RunAsync(session, [new QueryParam("rc", "refcursor"), new QueryParam("n", "int", JsonValue.Create(3))],
            "BEGIN OPEN :rc FOR SELECT LEVEL AS n FROM dual CONNECT BY LEVEL <= :n; END;");
        Assert.True(summary.Status == ExecutionStatus.Ok, string.Join("; ", sink.Errors.Select(e => e.Error.Message)));
        var rs = Assert.Single(sink.ResultSets);
        Assert.Equal(3, rs.Rows.Count);
    }

    [SkippableFact]
    public async Task M15_OutParams_AreReturned()
    {
        RequireAvailable();
        await using var session = await Fixture.OpenSessionAsync();
        var (summary, sink) = await RunAsync(session, [new QueryParam("x", "int", null, "out"), new QueryParam("s", "string", null, "out")],
            "BEGIN :x := 41 + 1; :s := 'hello'; END;");
        Assert.True(summary.Status == ExecutionStatus.Ok, string.Join("; ", sink.Errors.Select(e => e.Error.Message)));
        Assert.Equal([("x", (object?)"42"), ("s", "hello")], summary.OutParams!.Select(o => (o.Name, o.Value)));
    }

    [SkippableFact]
    public async Task M15_UnboundBind_StillReportsBindVarsUnsupported()
    {
        RequireAvailable();
        await using var session = await Fixture.OpenSessionAsync();
        var (summary, sink) = await RunAsync(session, [new QueryParam("a", "int", JsonValue.Create(1))], "SELECT :a, :b FROM dual");
        Assert.Equal(ExecutionStatus.Error, summary.Status);
        var error = Assert.Single(sink.Errors).Error;
        Assert.Equal(ErrorCodes.BindVarsUnsupported, error.Code);
        Assert.Equal("b", error.Detail);
    }
