    [Fact]
    public void Identifiers_FoldAndQuote()
    {
        Assert.Equal("CUSTOMERS", OracleDdlScripter.Fold("customers"));
        Assert.Equal("MixedCase", OracleDdlScripter.Fold("MixedCase"));
        Assert.Equal("lower q", OracleDdlScripter.Fold("\"lower q\""));
        Assert.Equal("CUSTOMERS", OracleDdlScripter.Ident("customers"));
        Assert.Equal("\"MixedCase\"", OracleDdlScripter.Ident("MixedCase"));
        Assert.Equal("\"DATE\"", OracleDdlScripter.Ident("date")); // reserved
        // Lower-case model names are the same objects as the stored upper-case ones: no spurious renames.
        var orders = DesignerCases.Orders(Dialect.PlSql);
        var lower = orders with { Name = "orders", Columns = orders.Columns.Select(c => c with { Name = c.Name.ToLowerInvariant(), Id = c.Id!.ToLowerInvariant() }).ToList() };
        Assert.Empty(Scripter.ScriptTable(orders, lower, Context).Statements);
    }

    [Fact]
    public void OnUpdate_IsIgnoredWithWarning_AndSetDefaultFallsBack()
    {
        var orders = DesignerCases.Orders(Dialect.PlSql);
        var desired = orders with { ForeignKeys = [orders.ForeignKeys[0] with { OnUpdate = "CASCADE", OnDelete = "SET NULL" }] };
        var script = Scripter.ScriptTable(orders, desired, Context);
        Assert.Contains("Oracle ignores ON UPDATE actions.", script.Warnings);
        Assert.Contains(script.Statements, s => s.Sql.EndsWith("ON DELETE SET NULL", StringComparison.Ordinal));
        Assert.DoesNotContain(script.Statements, s => s.Sql.Contains("ON UPDATE", StringComparison.Ordinal));
    }

    [Fact]
    public void Views_OrReplace_Force_Rename()
    {
        // Renamed: a plain CREATE of the new name (ORA-00955 when it exists, never replaced), then the old view dropped.
        // The original name is the stored spelling (as read from the server); the new name folds to upper case.
        var s = Scripter.ScriptView(new ViewDefinition(null, "order_totals", "TOTALS", "SELECT customer_id, SUM(total) total FROM orders GROUP BY customer_id;\n/", new ViewOptions(Force: true, CheckOption: true)), Context);
        Assert.False(s.Transactional);
        Assert.Equal(2, s.Statements.Count);
        Assert.Equal("CREATE FORCE VIEW SHOP.ORDER_TOTALS AS\nSELECT customer_id, SUM(total) total FROM orders GROUP BY customer_id\nWITH CHECK OPTION", s.Statements[0].Sql);
        Assert.Equal("DROP VIEW SHOP.TOTALS", s.Statements[1].Sql);
        Golden.Match("plsql_view_rename.sql", Golden.Render(s));

        // New view: plain CREATE. Editing the same view (names fold to upper case): CREATE OR REPLACE.
        var created = Scripter.ScriptView(new ViewDefinition(null, "order_totals", null, "SELECT 1 x FROM dual", new ViewOptions()), Context);
        Assert.Equal("CREATE VIEW SHOP.ORDER_TOTALS AS\nSELECT 1 x FROM dual", Assert.Single(created.Statements).Sql);
        var edited = Scripter.ScriptView(new ViewDefinition(null, "order_totals", "ORDER_TOTALS", "SELECT 1 x FROM dual", new ViewOptions()), Context);
        Assert.Equal("CREATE OR REPLACE VIEW SHOP.ORDER_TOTALS AS\nSELECT 1 x FROM dual", Assert.Single(edited.Statements).Sql);

        // A stored lower-case (quoted) view keeps its exact name when edited, and is dropped by it when renamed.
        var lower = Scripter.ScriptView(new ViewDefinition("SHOP", "order_totals", "order_totals", "SELECT 1 x FROM dual", new ViewOptions()), Context);
        Assert.Equal("CREATE OR REPLACE VIEW SHOP.\"order_totals\" AS\nSELECT 1 x FROM dual", Assert.Single(lower.Statements).Sql);
        var renamed = Scripter.ScriptView(new ViewDefinition("SHOP", "totals2", "order_totals", "SELECT 1 x FROM dual", new ViewOptions()), Context);
        Assert.Equal("CREATE VIEW SHOP.TOTALS2 AS\nSELECT 1 x FROM dual", renamed.Statements[0].Sql);
        Assert.Equal("DROP VIEW SHOP.\"order_totals\"", renamed.Statements[1].Sql);
    }

    /// <summary>
    /// A table whose stored names are lower case (created quoted: "lower_tab", columns "id", "select") is altered by
    /// those exact names; only names the user typed anew fold to upper case.
    /// </summary>
    [Fact]
    public void StoredLowerCaseNames_AreNotFolded()
    {
        var original = new TableModel
        {
            Schema = "SHOP", Name = "lower_tab",
            Columns =
            [
                new TableColumnModel { Id = "id", Name = "id", Type = "NUMBER(10)", Nullable = false },
                new TableColumnModel { Id = "Name", Name = "Name", Type = "VARCHAR2(30)" },
                new TableColumnModel { Id = "select", Name = "select", Type = "VARCHAR2(10)" },
            ],
            PrimaryKey = new PrimaryKeyModel { Name = "SYS_C001", Columns = ["id"] },
        };
        var desired = original with
        {
            Columns =
            [
                original.Columns[0],
                original.Columns[1] with { Name = "full_name", Type = "VARCHAR2(60)", Comment = "c" },
                new TableColumnModel { Name = "newcol", Type = "NUMBER(5)" },
            ],
        };
        var sql = Scripter.ScriptTable(original, desired, Context).Statements.Select(s => s.Sql).ToList();
        Assert.Equal(
        [
            "ALTER TABLE SHOP.\"lower_tab\" DROP COLUMN \"select\"",
            "ALTER TABLE SHOP.\"lower_tab\" RENAME COLUMN \"Name\" TO FULL_NAME",
            "ALTER TABLE SHOP.\"lower_tab\" MODIFY (FULL_NAME VARCHAR2(60))",
            "ALTER TABLE SHOP.\"lower_tab\" ADD (NEWCOL NUMBER(5))",
            "COMMENT ON COLUMN SHOP.\"lower_tab\".FULL_NAME IS 'c'",
        ], sql);
        // Unchanged: no statements (the stored names are not "renamed" to their folded spelling).
        Assert.Empty(Scripter.ScriptTable(original, original, Context).Statements);
    }
}

public sealed class OraclePlanReaderTests
{
    private static OraclePlanReader.PlanRow R(int id, int? parent, string op, string? options, string? obj, double? cost, double? card, string? access = null, string? filter = null) =>
        new(id, parent, op, options, obj is null ? null : "SHOP", obj, cost, card, card * 20, access, filter);

    public static IReadOnlyList<OraclePlanReader.PlanRow> SampleRows =>
    [
        R(0, null, "SELECT STATEMENT", null, null, 7, 12),
        R(1, 0, "HASH", "GROUP BY", null, 7, 12),
        R(2, 1, "HASH JOIN", null, null, 6, 120, "\"O\".\"CUSTOMER_ID\"=\"C\".\"ID\""),
        R(3, 2, "TABLE ACCESS", "FULL", "CUSTOMERS", 3, 300),
        R(4, 2, "TABLE ACCESS", "BY INDEX ROWID BATCHED", "ORDERS", 3, 120),
        R(5, 4, "INDEX", "RANGE SCAN", "IX_ORDERS_DATE", 1, 120, "\"O\".\"ORDER_DATE\">=:SINCE"),
    ];

    [Fact]
    public void BuildTree_FromPlanTableRows()
    {
        var root = OraclePlanReader.BuildTree(SampleRows);
        Assert.Equal("SELECT STATEMENT", root.Op);
        var join = root.Children.Single().Children.Single();
        Assert.Equal("HASH JOIN", join.Op);
        Assert.Equal("\"O\".\"CUSTOMER_ID\"=\"C\".\"ID\"", join.Predicate);
        Assert.Equal(["TABLE ACCESS FULL", "TABLE ACCESS BY INDEX ROWID BATCHED"], join.Children.Select(c => c.Op));
        Assert.Equal("SHOP.CUSTOMERS", join.Children[0].Object);
        Assert.Contains("Full table scan of SHOP.CUSTOMERS", join.Children[0].Warnings);
        Assert.Equal("INDEX RANGE SCAN", join.Children[1].Children.Single().Op);
        Assert.InRange(root.DescendantsAndSelf().Sum(n => n.CostPct ?? 0), 99.5, 100.5);
        Assert.Equal(42.9, join.Children[0].CostPct); // 3 / 7

        Golden.MatchUiFixture("plans/oracle-estimated.json", new ExecPlanEvent("x_fixture", Dialect.PlSql, "estimated", root,
            "Plan hash value: 1234567890\n\n-------------------------------------------------------------\n| Id  | Operation                    | Name           | Rows  |\n-------------------------------------------------------------\n|   0 | SELECT STATEMENT             |                |    12 |\n|   1 |  HASH GROUP BY               |                |    12 |\n|*  2 |   HASH JOIN                  |                |   120 |\n|   3 |    TABLE ACCESS FULL         | CUSTOMERS      |   300 |\n|   4 |    TABLE ACCESS BY INDEX ROWID BATCHED| ORDERS |   120 |\n|*  5 |     INDEX RANGE SCAN         | IX_ORDERS_DATE |   120 |\n-------------------------------------------------------------",
            "text", []) { Ts = "2026-10-14T10:00:00.000Z" });
    }

    [Fact]
    public void ActualRows_AndEstimateWarnings()
    {
        var rows = new List<OraclePlanReader.PlanRow>
        {
            new(0, null, "SELECT STATEMENT", null, null, null, null, 1, null, null, null, ActualRows: 5000, Starts: 1),
            new(1, 0, "TABLE ACCESS", "FULL", "SHOP", "ORDERS", 10, 1, 8, null, "\"STATUS\"='new'", ActualRows: 5000, Starts: 1, ElapsedMicros: 12500),
        };
        var root = OraclePlanReader.BuildTree(rows);
        Assert.Equal(10, root.Cost); // statement row without cost takes the child's
        var scan = root.Children.Single();
        Assert.Equal(5000, scan.ActualRows);
        Assert.Contains(scan.Warnings, w => w.StartsWith("Row estimate off", StringComparison.Ordinal));
        Assert.Equal("12.5", scan.Props!["Actual elapsed (ms)"]);
        Assert.Equal("\"STATUS\"='new'", scan.Predicate);
    }

    [Fact]
    public void Script_ExplainPlanWithStatementId_AndNullBinds()
    {
        var reader = new OraclePlanReader();
        var est = reader.CreateScript(new ExplainInput("x_01ABCDEFGHJKMNPQRSTVWXYZ01", "SELECT * FROM orders WHERE id = :id AND total > :min;", ExplainModes.Estimated,
            [new QueryParam("id", "int", JsonValue.Create(1))], Line: 3));
        var batch = Assert.Single(est.Batches);
        Assert.Equal("EXPLAIN PLAN SET STATEMENT_ID = 'x_01ABCDEFGHJKMNPQRSTVWXYZ01' FOR\nSELECT * FROM orders WHERE id = :id AND total > :min", batch.Sql);
        Assert.Equal(2, batch.Line); // the statement starts on the batch's second line
        Assert.Equal(["id", "min"], est.Params!.Select(p => p.BareName));
        Assert.Equal("string", est.Params![1].Kind);

        var act = reader.CreateScript(new ExplainInput("x_1", "SELECT 1 FROM dual;", ExplainModes.Actual));
        Assert.Equal("ALTER SESSION SET STATISTICS_LEVEL = ALL", act.Batches[0].Sql);
        Assert.Equal("SELECT 1 FROM dual\n/* dbstudio:x_1 */", act.Batches[1].Sql);
        Assert.Equal(["ALTER SESSION SET STATISTICS_LEVEL = TYPICAL"], act.CleanupSql);
        Assert.Equal(30, OraclePlanReader.StatementId(new string('x', 40)).Length);
    }
}

public sealed class OracleParamBinderTests
{
    [Fact]
    public void Placeholders_IgnoreStringsCommentsAndTriggerCorrelationNames()
    {
        Assert.Equal(["id", "1", "Mixed"], OracleParamBinder.Instance.FindPlaceholders("SELECT :id, :1, :\"Mixed\", ':no', q'[:no]' FROM dual -- :no\n").Select(p => p.Name));
        Assert.Empty(OracleParamBinder.Instance.FindPlaceholders("CREATE OR REPLACE TRIGGER t BEFORE INSERT ON x FOR EACH ROW BEGIN :NEW.id := 1; END;"));
        Assert.DoesNotContain(OracleParamBinder.Instance.FindPlaceholders("BEGIN x := 1; END;"), p => p.Name is not null);
    }

    [Fact]
    public void Bind_TypedOracleParameters_AndRefCursorOutput()
    {
        using var cmd = new OracleCommand("BEGIN :total := f(:id, :d, :g); OPEN :rc FOR SELECT 1 FROM dual; END;") { BindByName = true };
        var bound = OracleParamBinder.Instance.Bind(cmd,
        [
            new QueryParam("total", "decimal", null, "out"), new QueryParam("id", "int", JsonValue.Create(5)),
            new QueryParam("d", "datetimeoffset", JsonValue.Create("2026-01-02T03:04:05+03:30")), new QueryParam("g", "guid", JsonValue.Create("00112233-4455-6677-8899-aabbccddeeff")),
            new QueryParam("rc", "refcursor"),
        ], new ParamBindCursor());
        var ps = cmd.Parameters.Cast<OracleParameter>().ToDictionary(p => p.ParameterName);
        Assert.Equal((OracleDbType.Decimal, ParameterDirection.Output), (ps["total"].OracleDbType, ps["total"].Direction));
        Assert.Equal(OracleDbType.Int64, ps["id"].OracleDbType);
        Assert.Equal(OracleDbType.TimeStampTZ, ps["d"].OracleDbType);
        Assert.Equal(new byte[] { 0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99, 0xAA, 0xBB, 0xCC, 0xDD, 0xEE, 0xFF }, (byte[])ps["g"].Value);
        Assert.Equal((OracleDbType.RefCursor, ParameterDirection.Output), (ps["rc"].OracleDbType, ps["rc"].Direction));
        Assert.Equal(2, bound.Outputs.Count());
    }

    /// <summary>
    /// NUMBER values beyond System.Decimal (up to 40 significant digits, as 1/3 is read back) bind as an exact
    /// OracleDecimal, so a grid edit neither rounds them nor fails the "verify unchanged" comparison.
    /// </summary>
    [Fact]
    public void Bind_DecimalBeyondSystemDecimal_IsExact()
    {
        static QueryParam P(string v) => new("p", ParamKinds.Decimal, JsonValue.Create(v));
        var third = global::Oracle.ManagedDataAccess.Types.OracleDecimal.Divide(1, 3);
        var exact = OracleParamBinder.ExactDecimal(P("0." + new string('3', 40)));
        Assert.NotNull(exact);
        Assert.Equal(third.ToString(), exact.Value.ToString());
        Assert.Equal("-1234567890123456789012345678901234.5678", OracleParamBinder.ExactDecimal(P("-1234567890123456789012345678901234.5678"))!.Value.ToString());
        Assert.Equal("0." + new string('0', 99) + "15", OracleParamBinder.ExactDecimal(P("1.5E-100"))!.Value.ToString());
        // System.Decimal holds these exactly: the ordinary decimal bind is kept.
        Assert.Null(OracleParamBinder.ExactDecimal(P("12.5")));
        Assert.Null(OracleParamBinder.ExactDecimal(P("12345678901234567890.25")));
        Assert.Null(OracleParamBinder.ExactDecimal(P("1.5E+3")));
        Assert.Null(OracleParamBinder.ExactDecimal(P("not a number")));

        using var cmd = new OracleCommand("SELECT :p FROM dual") { BindByName = true };
        OracleParamBinder.Instance.Bind(cmd, [P("0." + new string('3', 40))], new ParamBindCursor());
        var parameter = (OracleParameter)cmd.Parameters[0];
        Assert.Equal(OracleDbType.Decimal, parameter.OracleDbType);
        Assert.Equal(third.ToString(), parameter.Value!.ToString());
    }

    [Fact]
    public void ToWire_ConvertsOracleTypes()
    {
        Assert.Equal("12.5", OracleParamBinder.ToWire(new global::Oracle.ManagedDataAccess.Types.OracleDecimal(12.5m)));
        Assert.Null(OracleParamBinder.ToWire(global::Oracle.ManagedDataAccess.Types.OracleString.Null));
        Assert.Equal("x", OracleParamBinder.ToWire(new global::Oracle.ManagedDataAccess.Types.OracleString("x")));
    }
}

