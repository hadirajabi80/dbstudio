using System.Globalization;
using System.Text;
using DbStudio.Core.Models;
using DbStudio.Core.Providers;

namespace DbStudio.Providers.PostgreSql;

public sealed record PgIdentity(bool Always, long Start, long Increment);

/// <param name="Default">DEFAULT expression (null for identity and generated columns).</param>
/// <param name="Generated">GENERATED ALWAYS AS (expr) STORED expression.</param>
/// <param name="Collation">Non-default collation, already quoted.</param>
public sealed record PgColumnDefinition(string Name, string Type, bool Nullable, string? Default, PgIdentity? Identity, string? Generated, string? Collation, string? Comment);

/// <param name="Type">p primary key, u unique, c check, f foreign key, x exclusion.</param>
/// <param name="Definition"><c>pg_get_constraintdef(oid, true)</c>.</param>
public sealed record PgConstraintDefinition(string Name, string Type, string Definition, IReadOnlyList<string> Columns);

/// <param name="Definition"><c>pg_get_indexdef(oid)</c>.</param>
/// <param name="BacksConstraint">The index implements a PRIMARY KEY / UNIQUE / EXCLUDE constraint (scripted with it).</param>
public sealed record PgIndexDefinition(string Name, bool Unique, bool Primary, string Method, string Definition, string? Predicate,
    IReadOnlyList<string> KeyColumns, IReadOnlyList<string> IncludeColumns, IReadOnlyList<bool> Descending, bool BacksConstraint);

/// <param name="Kind">relkind: r table, p partitioned, f foreign, v view, m materialized view.</param>
public sealed record PgTableDefinition(string Schema, string Name, string Kind, bool Unlogged, string? Comment,
    IReadOnlyList<PgColumnDefinition> Columns, IReadOnlyList<PgConstraintDefinition> Constraints, IReadOnlyList<PgIndexDefinition> Indexes,
    IReadOnlyList<(string Name, string Definition)> Triggers, string? PartitionKey, IReadOnlyList<string>? Options,
    string? ForeignServer, IReadOnlyList<string>? ForeignOptions, long? RowEstimate, string? ViewDefinition);

public sealed record PgSequenceDefinition(string Type, long Start, long Increment, long Min, long Max, bool Cycle, long Cache, string? OwnedBy, string? Comment);

/// <param name="Kind">e enum, d domain, c composite, r range.</param>
public sealed record PgTypeDefinition(string Name, string Kind, string? Comment, IReadOnlyList<string> Labels, string? BaseType, bool NotNull,
    string? Default, uint Relation, string? RangeSubtype, IReadOnlyList<(string Name, string Definition)> Constraints,
    IReadOnlyList<(string Name, string Type)> Attributes);

/// <summary>
/// CREATE statements from catalog definitions (docs/PLAN-PG.md 2.5 DDL): tables with identity/generated columns and
/// <c>pg_get_constraintdef</c> constraints, partition keys, the non-constraint indexes (<c>pg_get_indexdef</c>), triggers
/// and COMMENT ON lines; views/materialized views from <c>pg_get_viewdef</c>; sequences and types generated.
/// </summary>
public sealed class PgDdlGenerator : IDdlGenerator
{
    private static readonly CultureInfo Inv = CultureInfo.InvariantCulture;

    /// <summary>Generic CREATE TABLE from catalog details (used when the full definition is not at hand).</summary>
    public string GenerateTableDdl(ObjectRef table, ObjectDetails details)
    {
        ArgumentNullException.ThrowIfNull(table);
        ArgumentNullException.ThrowIfNull(details);
        var name = PgSqlText.Qualify(table.Schema, table.Name);
        var parts = details.Columns.OrderBy(c => c.Ordinal).Select(c =>
        {
            var sb = new StringBuilder(PgSqlText.Quote(c.Name)).Append(' ').Append(c.Type);
            if (c.IsComputed && c.Default is not null) sb.Append(" GENERATED ALWAYS AS (").Append(c.Default).Append(") STORED");
            else if (c.IsIdentity && (c.Default is null || !c.Default.StartsWith("nextval(", StringComparison.Ordinal))) sb.Append(" GENERATED BY DEFAULT AS IDENTITY");
            else if (c.Default is not null) sb.Append(" DEFAULT ").Append(c.Default);
            if (!c.Nullable) sb.Append(" NOT NULL");
            return sb.ToString();
        }).ToList();
        var pk = details.Columns.Where(c => c.IsPk).OrderBy(c => c.Ordinal).Select(c => PgSqlText.Quote(c.Name)).ToList();
        if (pk.Count > 0) parts.Add($"PRIMARY KEY ({string.Join(", ", pk)})");
        foreach (var fk in details.ForeignKeys)
            parts.Add($"CONSTRAINT {PgSqlText.Quote(fk.Name)} FOREIGN KEY ({string.Join(", ", fk.Columns.Select(PgSqlText.Quote))}) " +
                      $"REFERENCES {PgSqlText.Qualify(fk.RefSchema, fk.RefTable)} ({string.Join(", ", fk.RefColumns.Select(PgSqlText.Quote))})");
        var ddl = new StringBuilder($"CREATE TABLE {name} (\n{string.Join(",\n", parts.Select(p => "    " + p))}\n);\n");
        foreach (var ix in details.Indexes.Where(i => !i.IsPrimaryKey))
            ddl.Append($"CREATE {(ix.Unique ? "UNIQUE " : "")}INDEX {PgSqlText.Quote(ix.Name)} ON {name} ({string.Join(", ", ix.Columns.Select(PgSqlText.Quote))});\n");
        return ddl.ToString();
    }

    /// <summary>CREATE [UNLOGGED|FOREIGN] TABLE … (columns, constraints) [PARTITION BY …] [WITH (…)], indexes, triggers, comments.</summary>
    public static string Generate(PgTableDefinition t)
    {
        var name = PgSqlText.Qualify(t.Schema, t.Name);
        var parts = t.Columns.Select(ColumnSql).ToList();
        foreach (var c in t.Constraints)
            parts.Add($"CONSTRAINT {PgSqlText.Quote(c.Name)} {c.Definition}");
        var head = t.Kind == "f" ? "CREATE FOREIGN TABLE" : t.Unlogged ? "CREATE UNLOGGED TABLE" : "CREATE TABLE";
        var sb = new StringBuilder($"{head} {name} (\n{string.Join(",\n", parts.Select(p => "    " + p))}\n)");
        if (!string.IsNullOrWhiteSpace(t.PartitionKey)) sb.Append("\nPARTITION BY ").Append(t.PartitionKey);
        if (t.Kind == "f" && t.ForeignServer is not null)
        {
            sb.Append("\nSERVER ").Append(PgSqlText.Quote(t.ForeignServer));
            if (t.ForeignOptions is { Count: > 0 } fo) sb.Append("\nOPTIONS (").Append(string.Join(", ", fo.Select(OptionSql))).Append(')');
        }
        if (t.Options is { Count: > 0 } options) sb.Append("\nWITH (").Append(string.Join(", ", options)).Append(')');
        sb.Append(";\n");
        AppendIndexesTriggersComments(sb, t, name, "TABLE");
        return sb.ToString();
    }

    /// <summary>CREATE OR REPLACE VIEW / CREATE MATERIALIZED VIEW from <c>pg_get_viewdef</c>, with options, indexes and comments.</summary>
    public static string ViewDdl(PgTableDefinition t)
    {
        var name = PgSqlText.Qualify(t.Schema, t.Name);
        var body = (t.ViewDefinition ?? "").Trim().TrimEnd(';').TrimEnd();
        var options = (t.Options ?? []).ToList();
        var check = options.FirstOrDefault(o => o.StartsWith("check_option=", StringComparison.OrdinalIgnoreCase));
        if (check is not null) options.Remove(check);
        var sb = new StringBuilder();
        if (t.Kind == "m")
        {
            sb.Append("CREATE MATERIALIZED VIEW ").Append(name);
            if (options.Count > 0) sb.Append(" WITH (").Append(string.Join(", ", options)).Append(')');
            sb.Append(" AS\n").Append(body).Append("\nWITH DATA;\n");
            AppendIndexesTriggersComments(sb, t, name, "MATERIALIZED VIEW");
            return sb.ToString();
        }
        sb.Append("CREATE OR REPLACE VIEW ").Append(name);
        if (options.Count > 0) sb.Append(" WITH (").Append(string.Join(", ", options)).Append(')');
        sb.Append(" AS\n").Append(body);
        if (check is not null) sb.Append("\nWITH ").Append(check["check_option=".Length..].ToUpperInvariant()).Append(" CHECK OPTION");
        sb.Append(";\n");
        AppendIndexesTriggersComments(sb, t, name, "VIEW");
        return sb.ToString();
    }

    private static void AppendIndexesTriggersComments(StringBuilder sb, PgTableDefinition t, string name, string objectKind)
    {
        foreach (var ix in t.Indexes.Where(i => !i.BacksConstraint)) sb.Append(ix.Definition.TrimEnd(';')).Append(";\n");
        foreach (var (_, def) in t.Triggers) sb.Append(def.TrimEnd(';')).Append(";\n");
        if (!string.IsNullOrWhiteSpace(t.Comment)) sb.Append($"COMMENT ON {objectKind} {name} IS {PgSqlText.Literal(t.Comment)};\n");
        foreach (var c in t.Columns.Where(c => !string.IsNullOrWhiteSpace(c.Comment)))
            sb.Append($"COMMENT ON COLUMN {name}.{PgSqlText.Quote(c.Name)} IS {PgSqlText.Literal(c.Comment!)};\n");
    }

    /// <summary><c>name type [COLLATE c] [GENERATED ALWAYS AS (e) STORED] [GENERATED … AS IDENTITY [(…)]] [DEFAULT e] [NOT NULL]</c>.</summary>
    public static string ColumnSql(PgColumnDefinition c)
    {
        var sb = new StringBuilder(PgSqlText.Quote(c.Name)).Append(' ').Append(c.Type);
        if (!string.IsNullOrEmpty(c.Collation)) sb.Append(" COLLATE ").Append(c.Collation);
        if (c.Generated is not null) sb.Append(" GENERATED ALWAYS AS (").Append(StripParens(c.Generated)).Append(") STORED");
        if (c.Identity is { } id)
        {
            sb.Append(id.Always ? " GENERATED ALWAYS AS IDENTITY" : " GENERATED BY DEFAULT AS IDENTITY");
            if (id.Start != 1 || id.Increment != 1)
                sb.Append(" (START WITH ").Append(id.Start.ToString(Inv)).Append(" INCREMENT BY ").Append(id.Increment.ToString(Inv)).Append(')');
        }
        if (c.Default is not null) sb.Append(" DEFAULT ").Append(c.Default);
        if (!c.Nullable) sb.Append(" NOT NULL");
        return sb.ToString();
    }

    public static string SequenceDdl(string qualifiedName, PgSequenceDefinition s)
    {
        var sb = new StringBuilder($"CREATE SEQUENCE {qualifiedName}\n    AS {s.Type}\n    START WITH {s.Start.ToString(Inv)}\n    INCREMENT BY {s.Increment.ToString(Inv)}\n" +
                                   $"    MINVALUE {s.Min.ToString(Inv)}\n    MAXVALUE {s.Max.ToString(Inv)}\n    CACHE {s.Cache.ToString(Inv)}\n    {(s.Cycle ? "CYCLE" : "NO CYCLE")}");
        if (s.OwnedBy is not null) sb.Append("\n    OWNED BY ").Append(s.OwnedBy);
        sb.Append(";\n");
        if (!string.IsNullOrWhiteSpace(s.Comment)) sb.Append($"COMMENT ON SEQUENCE {qualifiedName} IS {PgSqlText.Literal(s.Comment)};\n");
        return sb.ToString();
    }

    public static string TypeDdl(string qualifiedName, PgTypeDefinition t)
    {
        var sb = new StringBuilder();
        switch (t.Kind)
        {
            case "e":
                sb.Append($"CREATE TYPE {qualifiedName} AS ENUM ({string.Join(", ", t.Labels.Select(PgSqlText.Literal))});\n");
                break;
            case "d":
                sb.Append($"CREATE DOMAIN {qualifiedName} AS {t.BaseType}");
                if (t.Default is not null) sb.Append(" DEFAULT ").Append(t.Default);
                if (t.NotNull) sb.Append(" NOT NULL");
                foreach (var (name, def) in t.Constraints) sb.Append("\n    CONSTRAINT ").Append(PgSqlText.Quote(name)).Append(' ').Append(def);
                sb.Append(";\n");
                break;
            case "c":
                sb.Append($"CREATE TYPE {qualifiedName} AS (\n{string.Join(",\n", t.Attributes.Select(a => "    " + PgSqlText.Quote(a.Name) + " " + a.Type))}\n);\n");
                break;
            case "r":
                sb.Append($"CREATE TYPE {qualifiedName} AS RANGE (SUBTYPE = {t.RangeSubtype});\n");
                break;
            default:
                sb.Append($"-- Type {qualifiedName} ({t.Kind}) cannot be scripted.\n");
                break;
        }
        if (!string.IsNullOrWhiteSpace(t.Comment))
            sb.Append($"COMMENT ON {(t.Kind == "d" ? "DOMAIN" : "TYPE")} {qualifiedName} IS {PgSqlText.Literal(t.Comment)};\n");
        return sb.ToString();
    }

    /// <summary>"key=value" (pg reloptions / ftoptions) → <c>key 'value'</c>.</summary>
    private static string OptionSql(string option)
    {
        var eq = option.IndexOf('=');
        return eq < 0 ? option : $"{PgSqlText.Quote(option[..eq])} {PgSqlText.Literal(option[(eq + 1)..])}";
    }

    private static string StripParens(string expr)
    {
        var e = expr.Trim();
        return e.Length >= 2 && e[0] == '(' && e[^1] == ')' && Balanced(e[1..^1]) ? e[1..^1] : e;
    }

    private static bool Balanced(string s)
    {
        var depth = 0;
        foreach (var t in PgSqlText.Tokenize(s))
        {
            if (t.IsPunct('(')) depth++;
            else if (t.IsPunct(')') && --depth < 0) return false;
        }
        return depth == 0;
    }
}
