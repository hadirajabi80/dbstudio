using System.Text;
using DbStudio.Core.Models;
using DbStudio.Core.Providers;

namespace DbStudio.Providers.Oracle;

/// <summary>
/// CREATE TABLE from catalog metadata. Oracle normally uses DBMS_METADATA.GET_DDL; this generator is the fallback when
/// the user lacks the privilege (ORA-31603) and for callers that only have <see cref="ObjectDetails"/>.
/// </summary>
public sealed class OracleDdlGenerator : IDdlGenerator
{
    public string GenerateTableDdl(ObjectRef table, ObjectDetails details)
    {
        ArgumentNullException.ThrowIfNull(table);
        ArgumentNullException.ThrowIfNull(details);
        var full = (table.Schema is null ? "" : OracleSqlText.Quote(table.Schema) + ".") + OracleSqlText.Quote(table.Name);
        var lines = new List<string>();
        foreach (var c in details.Columns.OrderBy(c => c.Ordinal))
        {
            var sb = new StringBuilder(OracleSqlText.Quote(c.Name)).Append(' ').Append(c.Type);
            if (c.IsComputed && !string.IsNullOrWhiteSpace(c.Default))
            {
                sb.Append(" GENERATED ALWAYS AS (").Append(c.Default!.Trim()).Append(") VIRTUAL");
            }
            else
            {
                if (c.IsIdentity) sb.Append(" GENERATED BY DEFAULT AS IDENTITY");
                else if (!string.IsNullOrWhiteSpace(c.Default)) sb.Append(" DEFAULT ").Append(c.Default!.Trim());
                if (!c.Nullable) sb.Append(" NOT NULL");
            }
            lines.Add(sb.ToString());
        }

        var pkCols = details.Columns.Where(c => c.IsPk).OrderBy(c => c.Ordinal).Select(c => c.Name).ToList();
        var pkIndex = details.Indexes.FirstOrDefault(i => i.IsPrimaryKey);
        if (pkCols.Count == 0 && pkIndex is not null) pkCols = pkIndex.Columns.ToList();
        if (pkCols.Count > 0)
            lines.Add($"CONSTRAINT {OracleSqlText.Quote(pkIndex?.Name ?? "PK_" + table.Name)} PRIMARY KEY ({Cols(pkCols)})");
        foreach (var fk in details.ForeignKeys)
        {
            var refTable = (fk.RefSchema is null ? "" : OracleSqlText.Quote(fk.RefSchema) + ".") + OracleSqlText.Quote(fk.RefTable);
            lines.Add($"CONSTRAINT {OracleSqlText.Quote(fk.Name)} FOREIGN KEY ({Cols(fk.Columns)}) REFERENCES {refTable} ({Cols(fk.RefColumns)})");
        }

        var outSb = new StringBuilder("CREATE TABLE ").Append(full).Append(" (\n");
        outSb.Append(string.Join(",\n", lines.Select(l => "  " + l))).Append("\n);\n");

        foreach (var ix in details.Indexes.Where(i => !i.IsPrimaryKey))
        {
            outSb.Append("CREATE ").Append(ix.Unique ? "UNIQUE " : "")
                 .Append(ix.Type is "BITMAP" ? "BITMAP " : "")
                 .Append("INDEX ")
                 .Append(table.Schema is null ? "" : OracleSqlText.Quote(table.Schema) + ".").Append(OracleSqlText.Quote(ix.Name))
                 .Append(" ON ").Append(full).Append(" (").Append(Cols(ix.Columns)).Append(");\n");
        }
        foreach (var c in details.Columns.Where(c => !string.IsNullOrEmpty(c.Comment)).OrderBy(c => c.Ordinal))
            outSb.Append($"COMMENT ON COLUMN {full}.{OracleSqlText.Quote(c.Name)} IS {OracleSqlText.Literal(c.Comment!)};\n");
        return outSb.ToString();
    }

    // Function-based index columns arrive as SYS_NC... names; quoting keeps them recognisable.
    private static string Cols(IEnumerable<string> cols) => string.Join(", ", cols.Select(OracleSqlText.Quote));
}
