// The mock engine's PostgreSQL connection (docs/PLAN-PG.md 4.4): server info, databases, public + sales schemas with
// search_path, PG object fixtures and DDL, PostgreSQL error texts, LIMIT/OFFSET, ILIKE, RETURNING and $n binds.
import { describe, expect, it } from 'vitest';
import { inlinePgParams, MockEngine } from './engine';

function pg() {
  const e = new MockEngine();
  const info = e.createSession('c_pg', null, 'auto')!;
  return { e, s: e.sessions.get(info.sessionId)! };
}

describe('mock engine: PostgreSQL', () => {
  it('session: PostgreSQL 17.2, dialect pgsql, database shop', () => {
    const { s } = pg();
    expect(s.dialect).toBe('pgsql');
    expect(s.serverInfo.productVersion).toBe('17.2');
    expect(s.serverInfo.version).toMatch(/^PostgreSQL 17\.2/);
    expect(s.database).toBe('shop');
  });

  it('databases, schemas with search_path, snapshot', () => {
    const { e } = pg();
    expect(e.databases('c_pg')).toEqual({ databases: ['analytics', 'postgres', 'shop'], current: 'shop' });
    const sc = e.schemas('c_pg', 'shop');
    expect(sc.defaultSchema).toBe('public');
    expect(sc.schemas.map((x) => x.name)).toEqual(['public', 'sales']);
    expect(sc.schemas[0].searchPathIndex).toBe(2);
    expect(e.schemas('c_pg', 'analytics').schemas.map((x) => x.name)).toEqual(['public']);
    const snap = e.catalog('c_pg', 'shop', ['public', 'sales']);
    expect(snap.dialect).toBe('pgsql');
    expect(snap.searchPath).toEqual(['public']);
    const pub = snap.schemas.find((x) => x.name === 'public')!;
    const orders = pub.objects.find((o) => o.n === 'orders')!;
    expect(orders.c!.find((c) => c[0] === 'status')![1]).toBe('order_status');
    expect(orders.c!.find((c) => c[0] === 'id')!.slice(1, 5)).toEqual(['bigint', 0, 1, 1]);
    expect(pub.objects.find((o) => o.n === 'customers')!.c!.some((c) => c[1] === 'text[]')).toBe(true);
    expect(pub.objects.filter((o) => o.n === 'fn_tax')).toHaveLength(2);
    expect(pub.objects.find((o) => o.n === 'order_status')!.c!.map((c) => c[0])).toEqual(['new', 'paid', 'shipped', 'delivered', 'cancelled']);
    expect(pub.objects.find((o) => o.t === 'mview')!.n).toBe('customer_totals');
  });

  it('DDL of tables, functions, triggers and types', () => {
    const { e } = pg();
    expect(e.ddl('c_pg', { database: null, schema: 'public', name: 'orders', type: 'table' }).ddl).toContain('CREATE TABLE public.orders (\n    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL');
    expect(e.ddl('c_pg', { database: null, schema: 'public', name: 'add_order_line', type: 'proc' }).ddl).toMatch(/^CREATE OR REPLACE PROCEDURE public\.add_order_line/);
    expect(e.ddl('c_pg', { database: null, schema: 'public', name: 'trg_orders_check', type: 'trigger' }).ddl).toContain('EXECUTE FUNCTION public.trg_orders_check_fn()');
    expect(e.ddl('c_pg', { database: null, schema: 'public', name: 'order_status', type: 'type' }).ddl).toContain('AS ENUM');
  });

  it('PostgreSQL error texts and SQLSTATEs', () => {
    const { e, s } = pg();
    expect(e.interpret(s, 'SELECT * FROM nope')).toMatchObject({ error: 'relation "nope" does not exist', errorCode: '42P01' });
    expect(e.interpret(s, 'SELECT nope FROM orders')).toMatchObject({ error: 'column "nope" does not exist', errorCode: '42703' });
    expect(e.interpret(s, 'SELEC 1')).toMatchObject({ error: 'syntax error at or near "SELEC"', errorCode: '42601' });
    expect(e.interpret(s, 'DELETE FROM nope WHERE id = 1')).toMatchObject({ errorCode: '42P01' });
  });

  it('LIMIT / OFFSET paging and ILIKE', () => {
    const { e, s } = pg();
    const page = e.interpret(s, 'SELECT * FROM public.orders ORDER BY id LIMIT 10 OFFSET 20').sets[0];
    expect(page.rows).toHaveLength(10);
    expect(page.rows[0][0]).toBe(21);
    const found = e.interpret(s, "SELECT * FROM customers WHERE name ILIKE '%LOVELACE%'").sets[0];
    expect(found.rows.length).toBeGreaterThan(0);
  });

  it('INSERT … RETURNING answers with the new key', () => {
    const { e, s } = pg();
    const r = e.interpret(s, "INSERT INTO customers (name) VALUES ('x') RETURNING id");
    expect(r.affected).toBe(1);
    expect(r.sets[0].columns.map((c) => c.name)).toEqual(['id']);
    expect(typeof r.sets[0].rows[0][0]).toBe('number');
  });

  it('SHOW, DO and version()', () => {
    const { e, s } = pg();
    expect(e.interpret(s, 'SHOW search_path').sets[0].rows).toEqual([['"$user", public']]);
    expect(e.interpret(s, "DO $$ BEGIN RAISE NOTICE 'hi'; END $$").messages[0]).toMatchObject({ severity: 'info', text: 'hi' });
    expect(e.interpret(s, 'SELECT version()').sets[0].rows[0][0]).toMatch(/^PostgreSQL/);
  });

  it('$n, @name and :name binds are inlined (casts and strings untouched)', () => {
    const out = inlinePgParams("SELECT '$1', x::int FROM t WHERE a = $1 AND b = @name AND c = :c", [{ name: '1', value: 5 }, { name: 'name', value: "O'Brien" }, { name: 'c', value: true }]);
    expect(out).toBe("SELECT '$1', x::int FROM t WHERE a = 5 AND b = 'O''Brien' AND c = TRUE");
  });
});
