// WP-G mock additions: saved filters (`/filters`, PLAN-M1.5 3.7) and a MockEngine that understands the grid's
// generated DML with bind parameters (UPDATE/INSERT … RETURNING/DELETE by key and SELECT … WHERE key = @k).
// Register with `...createGridHandlers(store)` before the generic handlers; tests use them directly.
import { http, HttpResponse } from 'msw';
import type { CellValue, ColumnInfo, ExecuteRequest, QueryParam, SavedFilter, SavedFilterInput, SavedFilterPatch } from '../../api/types';
import { MockEngine, type MockEngineOptions } from '../engine';

const P = '*/api/v1';

export class FilterStoreMock {
  filters: SavedFilter[] = [];
  private seq = 0;
  list(connectionId: string | null, signature: string | null): SavedFilter[] {
    return this.filters.filter((f) => (!connectionId || f.connectionId === connectionId) && (!signature || f.signature === signature));
  }
  create(input: SavedFilterInput): SavedFilter {
    const f: SavedFilter = { ...input, id: `f_${++this.seq}`, createdAt: new Date().toISOString(), lastUsedAt: null };
    this.filters.push(f);
    return f;
  }
  update(id: string, patch: SavedFilterPatch): SavedFilter | null {
    const f = this.filters.find((x) => x.id === id);
    if (!f) return null;
    Object.assign(f, patch);
    return f;
  }
  remove(id: string): boolean {
    const n = this.filters.length;
    this.filters = this.filters.filter((x) => x.id !== id);
    return this.filters.length !== n;
  }
}

export function createGridHandlers(store: FilterStoreMock) {
  return [
    http.get(`${P}/filters`, ({ request }) => {
      const url = new URL(request.url);
      return HttpResponse.json(store.list(url.searchParams.get('connectionId'), url.searchParams.get('signature')));
    }),
    http.post(`${P}/filters`, async ({ request }) => {
      const body = (await request.json()) as SavedFilterInput;
      if (!body.name?.trim()) return HttpResponse.json({ error: { code: 'VALIDATION', message: 'name is required' } }, { status: 400 });
      return HttpResponse.json(store.create(body), { status: 201 });
    }),
    http.put(`${P}/filters/:id`, async ({ params, request }) => {
      const f = store.update(String(params.id), (await request.json()) as SavedFilterPatch);
      return f ? HttpResponse.json(f) : HttpResponse.json({ error: { code: 'NOT_FOUND', message: 'Filter not found' } }, { status: 404 });
    }),
    http.delete(`${P}/filters/:id`, ({ params }) =>
      store.remove(String(params.id)) ? new HttpResponse(null, { status: 204 }) : HttpResponse.json({ error: { code: 'NOT_FOUND', message: 'Filter not found' } }, { status: 404 })),
  ];
}

// ---------------------------------------------------------------- DML-aware engine

export interface MockTable {
  columns: ColumnInfo[];
  rows: CellValue[][];
  key: string;
  /** Next identity value for the key. */
  nextId: number;
}

type Interpreted = ReturnType<MockEngine['interpret']>;
type Session = Parameters<MockEngine['interpret']>[0];

const ident = (s: string) => s.replace(/^[["`]|[\]"`]$/g, '').toLowerCase();

/** MockEngine plus in-memory tables edited through parameterized statements (as generated by data/sqlgen). */
export class GridMockEngine extends MockEngine {
  tables = new Map<string, MockTable>();
  /** Every statement run with its binds (assertions). */
  log: { sql: string; params: QueryParam[] }[] = [];
  /** Force `UPDATE`/`DELETE` to affect 0 rows (conflict tests). */
  conflictOn: RegExp | null = null;
  private binds = new Map<string, QueryParam[]>();

  constructor(opts: MockEngineOptions = {}) {
    super(opts);
  }

  addTable(name: string, t: Omit<MockTable, 'nextId'>): void {
    const keyIdx = t.columns.findIndex((c) => c.name === t.key);
    const max = t.rows.reduce((m, r) => Math.max(m, Number(r[keyIdx]) || 0), 0);
    this.tables.set(name.toLowerCase(), { ...t, nextId: max + 1 });
  }

  override execute(sid: string, req: ExecuteRequest) {
    this.binds.set(sid, req.params ?? []);
    for (const b of req.batches) this.log.push({ sql: b.sql, params: req.params ?? [] });
    return super.execute(sid, req);
  }

  override interpret(s: Session, sqlRaw: string): Interpreted {
    const params = this.binds.get(s.sessionId) ?? [];
    const r = this.dml(sqlRaw.trim(), params);
    return r ?? super.interpret(s, sqlRaw);
  }

  private value(token: string, params: QueryParam[]): CellValue {
    const t = token.trim();
    const m = /^[@:]([A-Za-z_]\w*)$/.exec(t);
    if (m) return (params.find((p) => p.name === m[1])?.value ?? null) as CellValue;
    if (/^null$/i.test(t)) return null;
    if (/^-?\d+(\.\d+)?$/.test(t)) return Number(t);
    return t.replace(/^N?'|'$/g, '').replace(/''/g, "'");
  }

  private where(t: MockTable, clause: string, params: QueryParam[]): (row: CellValue[]) => boolean {
    const ors = clause.split(/\s+OR\s+/i).map((part) => part.replace(/^\(|\)$/g, '').split(/\s+AND\s+/i).map((cond) => {
      const isNull = /^(\S+)\s+IS\s+NULL$/i.exec(cond.trim());
      if (isNull) {
        const ci = t.columns.findIndex((c) => c.name.toLowerCase() === ident(isNull[1]));
        return (row: CellValue[]) => row[ci] === null;
      }
      const m = /^(\S+)\s*=\s*(\S+)$/.exec(cond.trim());
      if (!m) return () => false;
      const ci = t.columns.findIndex((c) => c.name.toLowerCase() === ident(m[1]));
      const v = this.value(m[2], params);
      return (row: CellValue[]) => row[ci] !== null && String(row[ci]) === String(v);
    }));
    return (row) => ors.some((ands) => ands.every((f) => f(row)));
  }

  private out(): Interpreted {
    return { sets: [], messages: [], affected: null, kind: null, error: null };
  }

  private dml(sql: string, params: QueryParam[]): Interpreted | null {
    let m = /^UPDATE\s+(?:\S+\.)?(\S+)\s+SET\s+(.+?)\s+WHERE\s+(.+)$/is.exec(sql);
    if (m) {
      const t = this.tables.get(ident(m[1]));
      if (!t) return null;
      const sets = m[2].split(/\s*,\s*/).map((a) => a.split(/\s*=\s*/));
      const pred = this.where(t, m[3], params);
      let n = 0;
      if (!this.conflictOn?.test(sql)) {
        for (const row of t.rows) {
          if (!pred(row)) continue;
          for (const [c, v] of sets) row[t.columns.findIndex((x) => x.name.toLowerCase() === ident(c))] = this.value(v, params);
          n++;
        }
      }
      return { ...this.out(), affected: n, kind: 'UPDATE' };
    }
    m = /^DELETE\s+FROM\s+(?:\S+\.)?(\S+)\s+WHERE\s+(.+)$/is.exec(sql);
    if (m) {
      const t = this.tables.get(ident(m[1]));
      if (!t) return null;
      const pred = this.where(t, m[2], params);
      const before = t.rows.length;
      if (!this.conflictOn?.test(sql)) t.rows = t.rows.filter((r) => !pred(r));
      return { ...this.out(), affected: before - t.rows.length, kind: 'DELETE' };
    }
    m = /^INSERT\s+INTO\s+(?:\S+\.)?(\S+)\s*(?:\(([^)]*)\))?\s*(?:OUTPUT\s+\S+\s+)?(?:VALUES\s*\((.*?)\)|DEFAULT VALUES)(?:\s+RETURNING\s+(\S+))?$/is.exec(sql);
    if (m) {
      const t = this.tables.get(ident(m[1]));
      if (!t) return null;
      if (/\bfail\b/i.test(JSON.stringify(params))) {
        return { ...this.out(), error: 'NOT NULL constraint failed: mock insert rejected', errorCode: '19' };
      }
      const cols = m[2] ? m[2].split(/\s*,\s*/).map(ident) : [];
      const vals = m[3] ? m[3].split(/\s*,\s*/) : [];
      const row: CellValue[] = t.columns.map(() => null);
      cols.forEach((c, i) => (row[t.columns.findIndex((x) => x.name.toLowerCase() === c)] = this.value(vals[i], params)));
      const ki = t.columns.findIndex((c) => c.name === t.key);
      if (row[ki] === null) row[ki] = t.nextId++;
      t.rows.push(row);
      const res: Interpreted = { ...this.out(), affected: 1, kind: 'INSERT' };
      if (m[4] || /OUTPUT/i.test(sql)) res.sets.push({ columns: [t.columns[ki]], rows: [[row[ki]]] });
      return res;
    }
    m = /^SELECT\s+\*\s+FROM\s+(?:\S+\.)?(\S+)\s+WHERE\s+(.+)$/is.exec(sql);
    if (m && /[@:]k\d/.test(m[2])) {
      const t = this.tables.get(ident(m[1]));
      if (!t) return null;
      const pred = this.where(t, m[2], params);
      return { ...this.out(), sets: [{ columns: t.columns, rows: t.rows.filter(pred).map((r) => [...r]) }] };
    }
    return null;
  }
}
