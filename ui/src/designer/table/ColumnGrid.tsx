// Keyboard-first column grid of the table designer: a plain accessible <table role="grid"> with a roving tabindex.
//   Navigation: arrows, Home/End, Ctrl+Home/End, Tab/Shift+Tab (next/previous cell), Page Up/Down.
//   Editing: Enter/F2 or typing starts editing a text cell; Enter commits and moves down, Tab commits and moves right,
//            Esc cancels. Space/Enter toggles Null / PK / Identity cells.
//   Rows: Insert adds a column below, Del removes the column, Alt+Up/Down reorders, Ctrl+D duplicates.
import { KeyRound, Plus } from 'lucide-react';
import { useEffect, useLayoutEffect, useMemo, useRef, useState, type KeyboardEvent } from 'react';
import type { DesignerFeatures, DesignerType, Dialect, TableColumnModel, TableModel } from '../../api/types';

export type ColumnKey = 'name' | 'type' | 'nullable' | 'pk' | 'identity' | 'default' | 'comment';

interface ColumnDef {
  key: ColumnKey;
  label: string;
  kind: 'text' | 'check' | 'type';
  title?: string;
}

export interface ColumnGridProps {
  table: TableModel;
  dialect: Dialect;
  types: DesignerType[];
  features: DesignerFeatures | null;
  readOnly: boolean;
  /** Column indexes with validation errors. */
  errorRows: Set<number>;
  active: number;
  onActiveChange(row: number): void;
  onChange(index: number, patch: Partial<TableColumnModel>): void;
  onTogglePk(index: number): void;
  onAdd(at: number): void;
  onRemove(index: number): void;
  onMove(index: number, delta: number): void;
  onDuplicate(index: number): void;
}

function columnsFor(dialect: Dialect, features: DesignerFeatures | null): ColumnDef[] {
  const cols: ColumnDef[] = [
    { key: 'name', label: 'Name', kind: 'text' },
    { key: 'type', label: 'Type', kind: 'type' },
    { key: 'nullable', label: 'Null', kind: 'check', title: 'Allows NULL' },
    { key: 'pk', label: 'PK', kind: 'check', title: 'Primary key' },
  ];
  if (dialect === 'sqlite') cols.push({ key: 'identity', label: 'Auto', kind: 'check', title: 'INTEGER PRIMARY KEY AUTOINCREMENT' });
  else if (features?.identity !== false) cols.push({ key: 'identity', label: 'Identity', kind: 'check', title: dialect === 'plsql' ? 'GENERATED BY DEFAULT AS IDENTITY' : 'IDENTITY(1,1)' });
  cols.push({ key: 'default', label: 'Default', kind: 'text' });
  if (features?.comments !== false && dialect !== 'sqlite') cols.push({ key: 'comment', label: 'Comment', kind: 'text' });
  return cols;
}

const isPrintable = (e: KeyboardEvent) => e.key.length === 1 && !e.ctrlKey && !e.metaKey && !e.altKey;

export function ColumnGrid(p: ColumnGridProps) {
  const { table, dialect } = p;
  const cols = useMemo(() => columnsFor(dialect, p.features), [dialect, p.features]);
  const rowCount = table.columns.length + 1; // + the "add column" row
  const [cell, setCell] = useState<{ row: number; col: number }>({ row: Math.min(p.active, table.columns.length), col: 0 });
  const [editing, setEditing] = useState<{ row: number; col: number; value: string; typed?: boolean } | null>(null);
  const tableRef = useRef<HTMLTableElement>(null);
  const focusPending = useRef(false);
  /** True once the current edit was committed or cancelled (a blur after Esc/Enter must not commit again). */
  const editDone = useRef(true);
  const beginEdit = (e: { row: number; col: number; value: string; typed?: boolean }) => {
    editDone.current = false;
    setEditing(e);
  };
  const pk = table.primaryKey?.columns ?? [];

  // Keep the cursor inside the grid when rows go away.
  useEffect(() => {
    if (cell.row > table.columns.length) setCell((c) => ({ ...c, row: table.columns.length }));
  }, [table.columns.length, cell.row]);

  useEffect(() => {
    if (cell.row < table.columns.length && cell.row !== p.active) p.onActiveChange(cell.row);
  }, [cell.row]); // eslint-disable-line react-hooks/exhaustive-deps

  useLayoutEffect(() => {
    if (!focusPending.current) return;
    focusPending.current = false;
    const el = tableRef.current?.querySelector<HTMLElement>(editing ? '.dz-editing input' : `[data-cell="${cell.row}:${cell.col}"]`);
    el?.focus();
    // Enter/F2 selects the value; typing a character keeps it and continues after it.
    if (editing && el instanceof HTMLInputElement) {
      if (editing.typed) el.setSelectionRange(el.value.length, el.value.length);
      else el.select();
    }
  });

  const moveTo = (row: number, col: number) => {
    const r = Math.max(0, Math.min(rowCount - 1, row));
    const c = r === table.columns.length ? 0 : Math.max(0, Math.min(cols.length - 1, col));
    focusPending.current = true;
    setCell({ row: r, col: c });
  };

  const valueOf = (row: number, key: ColumnKey): string => {
    const c = table.columns[row];
    if (!c) return '';
    if (key === 'name') return c.name;
    if (key === 'type') return c.computed ? '' : c.type;
    if (key === 'default') return c.default ?? '';
    if (key === 'comment') return c.comment ?? '';
    return '';
  };

  const checked = (row: number, key: ColumnKey): boolean => {
    const c = table.columns[row];
    if (!c) return false;
    if (key === 'nullable') return c.nullable;
    if (key === 'pk') return pk.includes(c.name);
    if (key === 'identity') return dialect === 'sqlite' ? c.autoincrement : !!c.identity;
    return false;
  };

  const toggle = (row: number, key: ColumnKey) => {
    if (p.readOnly) return;
    const c = table.columns[row];
    if (!c) return;
    if (key === 'nullable') p.onChange(row, { nullable: !c.nullable });
    else if (key === 'pk') p.onTogglePk(row);
    else if (key === 'identity') {
      if (dialect === 'sqlite') p.onChange(row, { autoincrement: !c.autoincrement, ...(c.autoincrement ? {} : { type: 'INTEGER' }) });
      else p.onChange(row, { identity: c.identity ? null : { seed: 1, increment: 1 } });
    }
  };

  const startEdit = (initial?: string) => {
    if (p.readOnly) return;
    const def = cols[cell.col];
    if (cell.row >= table.columns.length || def.kind === 'check') return;
    focusPending.current = true;
    beginEdit({ row: cell.row, col: cell.col, value: initial ?? valueOf(cell.row, def.key), typed: initial !== undefined });
  };

  /** Commit the edit of cell `at` (captured when editing started, so a click elsewhere cannot retarget it). */
  const commit = (at: { row: number; col: number }, value: string) => {
    if (editDone.current) return;
    editDone.current = true;
    const def = cols[at.col];
    const row = at.row;
    setEditing(null);
    if (p.readOnly || row >= table.columns.length) return;
    if (value === valueOf(row, def.key)) return;
    if (def.key === 'name') p.onChange(row, { name: value.trim() });
    else if (def.key === 'type') p.onChange(row, { type: value.trim() });
    else if (def.key === 'default') p.onChange(row, { default: value.trim() ? value : null });
    else if (def.key === 'comment') p.onChange(row, { comment: value.trim() ? value : null });
  };

  const onCellKey = (e: KeyboardEvent<HTMLTableCellElement>) => {
    if (editing) return;
    const { row, col } = cell;
    const def = cols[col];
    const onAddRow = row === table.columns.length;
    const k = e.key;
    let handled = true;
    if (k === 'ArrowDown' && e.altKey) {
      if (!onAddRow && row < table.columns.length - 1 && !p.readOnly) {
        p.onMove(row, 1);
        moveTo(row + 1, col);
      }
    } else if (k === 'ArrowUp' && e.altKey) {
      if (!onAddRow && row > 0 && !p.readOnly) {
        p.onMove(row, -1);
        moveTo(row - 1, col);
      }
    } else if (k === 'ArrowDown') moveTo(row + 1, col);
    else if (k === 'ArrowUp') moveTo(row - 1, col);
    else if (k === 'ArrowRight') moveTo(row, col + 1);
    else if (k === 'ArrowLeft') moveTo(row, col - 1);
    else if (k === 'Home') moveTo(e.ctrlKey ? 0 : row, 0);
    else if (k === 'End') moveTo(e.ctrlKey ? rowCount - 1 : row, cols.length - 1);
    else if (k === 'PageDown') moveTo(row + 10, col);
    else if (k === 'PageUp') moveTo(row - 10, col);
    else if (k === 'Tab') {
      const dir = e.shiftKey ? -1 : 1;
      let r = row;
      let c = col + dir;
      if (onAddRow) {
        if (dir > 0) handled = false;
        else {
          r = row - 1;
          c = cols.length - 1;
        }
      } else if (c >= cols.length) {
        r = row + 1;
        c = 0;
      } else if (c < 0) {
        if (row === 0) handled = false;
        r = row - 1;
        c = cols.length - 1;
      }
      if (handled) moveTo(r, c);
    } else if (onAddRow && (k === 'Enter' || k === ' ' || k === 'Insert')) {
      if (!p.readOnly) {
        p.onAdd(table.columns.length);
        focusPending.current = true;
        setCell({ row: table.columns.length, col: 0 });
        beginEdit({ row: table.columns.length, col: 0, value: '' });
      }
    } else if (k === 'Insert' && !p.readOnly) {
      p.onAdd(row + 1);
      focusPending.current = true;
      setCell({ row: row + 1, col: 0 });
      beginEdit({ row: row + 1, col: 0, value: '' });
    } else if (k === 'Delete' && !onAddRow && !p.readOnly) {
      p.onRemove(row);
      moveTo(Math.min(row, table.columns.length - 1), col);
    } else if ((k === 'd' || k === 'D') && (e.ctrlKey || e.metaKey) && !onAddRow && !p.readOnly) {
      p.onDuplicate(row);
      moveTo(row + 1, col);
    } else if (def?.kind === 'check' && (k === ' ' || k === 'Enter') && !onAddRow) {
      toggle(row, def.key);
    } else if ((k === 'Enter' || k === 'F2') && !onAddRow) {
      startEdit();
    } else if (isPrintable(e) && !onAddRow && def?.kind !== 'check') {
      startEdit(k);
    } else handled = false;
    if (handled) {
      e.preventDefault();
      e.stopPropagation();
    }
  };

  const onEditKey = (at: { row: number; col: number }, e: KeyboardEvent<HTMLInputElement>, value: string, fromList?: string | null) => {
    if (e.key === 'Escape') {
      e.preventDefault();
      e.stopPropagation();
      editDone.current = true;
      setEditing(null);
      focusPending.current = true;
    } else if (e.key === 'Enter') {
      e.preventDefault();
      e.stopPropagation();
      commit(at, fromList ?? value);
      moveTo(at.row + 1 < table.columns.length ? at.row + 1 : at.row, at.col);
    } else if (e.key === 'Tab') {
      e.preventDefault();
      e.stopPropagation();
      commit(at, fromList ?? value);
      const dir = e.shiftKey ? -1 : 1;
      let c = at.col + dir;
      let r = at.row;
      if (c >= cols.length) {
        c = 0;
        r++;
      } else if (c < 0) {
        c = cols.length - 1;
        r--;
      }
      moveTo(r, c);
    }
  };

  return (
    <table
      ref={tableRef}
      className="dz-grid"
      role="grid"
      aria-label="Columns"
      aria-rowcount={rowCount + 1}
      aria-colcount={cols.length + 1}
      aria-readonly={p.readOnly || undefined}
    >
      <thead>
        <tr role="row" aria-rowindex={1}>
          <th role="columnheader" aria-colindex={1}>
            #
          </th>
          {cols.map((c, i) => (
            <th key={c.key} role="columnheader" aria-colindex={i + 2} title={c.title}>
              {c.label}
            </th>
          ))}
        </tr>
      </thead>
      <tbody>
        {table.columns.map((c, row) => (
          <tr
            key={`${c.id ?? ''}\u0001${row}`}
            role="row"
            aria-rowindex={row + 2}
            aria-selected={row === cell.row}
            className={`${row === cell.row ? 'dz-row-active' : ''}${p.errorRows.has(row) ? ' dz-row-error' : ''}`}
          >
            <td className="dz-num" role="rowheader" aria-colindex={1}>
              {row + 1}
            </td>
            {cols.map((def, col) => {
              const isActive = row === cell.row && col === cell.col;
              const isEditing = !!editing && editing.row === row && editing.col === col;
              const at = { row, col };
              const common = {
                role: 'gridcell',
                'aria-colindex': col + 2,
                'data-cell': `${row}:${col}`,
                tabIndex: isActive && !isEditing ? 0 : -1,
                onKeyDown: onCellKey,
                onMouseDown: () => {
                  if (!isActive) {
                    setEditing(null);
                    setCell({ row, col });
                  }
                },
                // Focus from outside (screen reader, programmatic) moves the grid cursor too.
                onFocus: () => {
                  if (!isActive && !editing) setCell({ row, col });
                },
              } as const;
              if (def.kind === 'check') {
                const on = checked(row, def.key);
                const disabled = def.key === 'nullable' && pk.includes(c.name);
                return (
                  <td
                    key={def.key}
                    {...common}
                    className="dz-check"
                    aria-checked={on}
                    aria-disabled={disabled || p.readOnly || undefined}
                    aria-label={`${def.title ?? def.label}: ${on ? 'yes' : 'no'}`}
                    onClick={() => !disabled && toggle(row, def.key)}
                  >
                    <span className={`dz-mark${on ? ' on' : ''}`} aria-hidden="true">
                      {on ? def.key === 'pk' ? <KeyRound size={11} /> : '✓' : ''}
                    </span>
                    {def.key === 'pk' && on && pk.length > 1 && <span className="dz-pk-order">{pk.indexOf(c.name) + 1}</span>}
                  </td>
                );
              }
              if (isEditing) {
                return (
                  <td key={def.key} {...common} className="dz-editing">
                    {def.kind === 'type' ? (
                      <TypeEditor
                        initial={editing.value}
                        types={p.types}
                        onKey={(e, v, fromList) => onEditKey(at, e, v, fromList)}
                        onBlurCommit={(v) => commit(at, v)}
                        label={`Type of ${c.name}`}
                      />
                    ) : (
                      <input
                        className="dz-cell-input"
                        aria-label={`${def.label} of ${c.name || `column ${row + 1}`}`}
                        defaultValue={editing.value}
                        spellCheck={false}
                        onKeyDown={(e) => onEditKey(at, e, e.currentTarget.value)}
                        onBlur={(e) => commit(at, e.currentTarget.value)}
                      />
                    )}
                  </td>
                );
              }
              const v = valueOf(row, def.key);
              const computed = def.key === 'type' && c.computed;
              return (
                <td
                  key={def.key}
                  {...common}
                  className={def.key === 'name' || def.key === 'type' || def.key === 'default' ? `dz-mono${!v ? ' dz-placeholder' : ''}` : !v ? 'dz-placeholder' : ''}
                  onDoubleClick={() => startEdit()}
                  title={v || undefined}
                >
                  {computed ? <span className="dz-muted">AS ({c.computed!.expression})</span> : v || (def.key === 'name' ? 'name' : def.key === 'type' ? 'type' : '')}
                </td>
              );
            })}
          </tr>
        ))}
        <tr role="row" aria-rowindex={rowCount + 1}>
          <td className="dz-num" role="rowheader" aria-colindex={1}>
            <Plus size={12} aria-hidden="true" />
          </td>
          <td
            role="gridcell"
            aria-colindex={2}
            colSpan={cols.length}
            data-cell={`${table.columns.length}:0`}
            tabIndex={cell.row === table.columns.length ? 0 : -1}
            className="dz-placeholder"
            onKeyDown={onCellKey}
            onMouseDown={() => setCell({ row: table.columns.length, col: 0 })}
            onFocus={() => {
              if (cell.row !== table.columns.length && !editing) setCell({ row: table.columns.length, col: 0 });
            }}
            onClick={() => {
              if (p.readOnly) return;
              p.onAdd(table.columns.length);
              focusPending.current = true;
              setCell({ row: table.columns.length, col: 0 });
              beginEdit({ row: table.columns.length, col: 0, value: '' });
            }}
            aria-label="Add column (Enter)"
          >
            {p.readOnly ? '' : 'Add column (Enter or Insert)'}
          </td>
        </tr>
      </tbody>
    </table>
  );
}

/** Combobox for the type cell: free text plus the dialect's type list (filtered as you type). */
function TypeEditor(p: {
  initial: string;
  types: DesignerType[];
  label: string;
  onKey(e: KeyboardEvent<HTMLInputElement>, value: string, fromList?: string | null): void;
  onBlurCommit(value: string): void;
}) {
  const [value, setValue] = useState(p.initial);
  const [sel, setSel] = useState(-1);
  const listId = useRef(`dz-types-${Math.random().toString(36).slice(2, 8)}`).current;
  const q = value.trim().toLowerCase();
  const matches = useMemo(() => {
    const all = p.types;
    if (!q) return all.slice(0, 40);
    const starts = all.filter((t) => t.name.toLowerCase().startsWith(q) || t.default.toLowerCase().startsWith(q));
    const contains = all.filter((t) => !starts.includes(t) && t.name.toLowerCase().includes(q));
    return [...starts, ...contains].slice(0, 40);
  }, [p.types, q]);
  const pick = sel >= 0 && sel < matches.length ? matches[sel] : null;
  /** Picking `nvarchar` while typing keeps a size the user already typed; else uses the type's default text. */
  const resolved = (t: DesignerType) => (/\(/.test(value) && value.toLowerCase().startsWith(t.name.toLowerCase()) ? value : t.default || t.name);
  return (
    <div className="dz-combo">
      <input
        className="dz-cell-input"
        role="combobox"
        aria-label={p.label}
        aria-expanded={matches.length > 0}
        aria-controls={listId}
        aria-autocomplete="list"
        aria-activedescendant={pick ? `${listId}-${sel}` : undefined}
        value={value}
        spellCheck={false}
        onChange={(e) => {
          setValue(e.target.value);
          setSel(-1);
        }}
        onKeyDown={(e) => {
          if (e.key === 'ArrowDown') {
            e.preventDefault();
            e.stopPropagation();
            setSel((s) => Math.min(matches.length - 1, s + 1));
            return;
          }
          if (e.key === 'ArrowUp') {
            e.preventDefault();
            e.stopPropagation();
            setSel((s) => Math.max(-1, s - 1));
            return;
          }
          p.onKey(e, value, pick ? resolved(pick) : null);
        }}
        onBlur={() => p.onBlurCommit(value)}
      />
      {matches.length > 0 && (
        <ul className="dz-combo-list" role="listbox" id={listId} aria-label="Types">
          {matches.map((t, i) => (
            <li
              key={t.name}
              id={`${listId}-${i}`}
              role="option"
              aria-selected={i === sel}
              onMouseDown={(e) => {
                e.preventDefault();
                setValue(resolved(t));
                setSel(-1);
              }}
            >
              <span>{t.default || t.name}</span>
              <span className="dz-sub">{t.category}</span>
            </li>
          ))}
        </ul>
      )}
    </div>
  );
}
