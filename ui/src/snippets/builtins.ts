// Built-in snippets per dialect (PLAN-M1.5 A4). Bodies use Monaco snippet syntax: `$1`, `${1:default}`, `$0`;
// `\t` is converted to the editor's indentation on insert.
import type { Dialect } from '../api/types';

export interface SnippetDef {
  id: string;
  name: string;
  prefix: string;
  /** null = every dialect. */
  dialects: Dialect[] | null;
  body: string;
  description?: string | null;
  builtin?: boolean;
}

const ALL = null;
const T: Dialect[] = ['tsql'];
const O: Dialect[] = ['plsql'];
const S: Dialect[] = ['sqlite'];
const P: Dialect[] = ['pgsql'];
const M: Dialect[] = ['mysql'];
/** Every SQL dialect but CQL (no CTEs, joins or CASE there). */
const NOT_CQL: Dialect[] = ['tsql', 'plsql', 'sqlite', 'pgsql', 'mysql', 'clickhouse', 'snowflake'];

function def(prefix: string, name: string, dialects: Dialect[] | null, body: string): SnippetDef {
  return { id: `builtin:${prefix}:${dialects ? dialects.join('+') : 'all'}`, name, prefix, dialects, body, builtin: true };
}

